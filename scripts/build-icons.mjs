// Turns assets/lucide-icons/*.svg (lucide-static 0.460) into src/icons.ts,
// keeping only the inner shapes so <hd-icon> can set size and stroke.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../assets/lucide-icons/', import.meta.url);
const out = new URL('../src/icons.ts', import.meta.url);

const entries = readdirSync(dir)
  .filter((f) => f.endsWith('.svg'))
  .sort()
  .map((f) => {
    const svg = readFileSync(new URL(f, dir), 'utf8');
    const inner = svg
      .slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'))
      .replace(/\s*\n\s*/g, '')
      .trim();
    return `  '${f.replace(/\.svg$/, '')}': '${inner}',`;
  });

writeFileSync(
  out,
  `// Generated by scripts/build-icons.mjs from assets/lucide-icons. Do not edit.\n` +
    `export const ICONS = {\n${entries.join('\n')}\n} as const;\n\n` +
    `export type IconName = keyof typeof ICONS;\n`,
);
console.log(`icons: ${entries.length} written to src/icons.ts`);
