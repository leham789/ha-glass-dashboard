// Only the canvas needs these: the grey behind a pop-up and the library's specimen boxes.
const CANVAS_ONLY = {
  light: { backdrop: '#D9DAE0', panel: '#E3E4E8' },
  dark: { backdrop: '#0B0C0E', panel: '#1E2024' },
};

function lines(vars, only, darkOnly) {
  const rows = [];
  for (const [canvas, card] of NAMES) {
    if (!card) {
      if (!darkOnly) rows.push(`\n  /* ${canvas} */`);
      continue;
    }
    const value = vars.get(`--glass-${card}`);
    if (value === undefined) {
      if (!darkOnly) throw new Error(`design-tokens: --glass-${card} is missing from src/tokens.ts`);
      continue;
    }
    rows.push(`  --${canvas}: ${value};`);
  }
  rows.push(darkOnly ? '' : '\n  /* canvas only */');
  for (const [k, v] of Object.entries(only)) rows.push(`  --${k}: ${v};`);
  return rows.join('\n');
}

const css = `/* Generated by scripts/build-design-tokens.mjs from src/tokens.ts. Do not edit:
   change src/tokens.ts and run \`npm run build\`, then publish this file to the
   canvas. Every frame links it, so the canvas and the cards share one set of values. */
:root {
${lines(light, CANVAS_ONLY.light, false)}
}

/* Dark mode: a frame's "theme" tweak sets data-theme="dark" (HA's dark theme
   does the same for the cards). Accent, status and light colours stay. */
[data-theme="dark"] {
${lines(dark, CANVAS_ONLY.dark, true)}

  color-scheme: dark;
}
/* the soft colour glows behind each screen dim in dark mode */
[data-theme="dark"] [style*="; filter: blur("] { opacity: 0.25 !important; }
`;

writeFileSync(out, css);
