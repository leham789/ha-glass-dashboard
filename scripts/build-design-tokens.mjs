// Writes design/tokens.css (the design canvas's colour and size list) from
// src/tokens.ts, so the canvas and the cards always use the same values.
// src/tokens.ts is the master: change a value there and run `npm run build`
// (or `npm run design-tokens`), then publish design/tokens.css to the canvas.
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../src/tokens.ts', import.meta.url), 'utf8');
const out = new URL('../design/tokens.css', import.meta.url);

/** The custom properties declared in the first `<selector> { … }` block. */
function block(selector) {
  const start = src.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`design-tokens: no "${selector}" block in src/tokens.ts`);
  const body = src.slice(start, src.indexOf('}', start));
  const vars = new Map();
  for (const m of body.matchAll(/(--glass-[\w-]+):\s*([^;]+);/g)) vars.set(m[1], m[2].trim());
  return vars;
}
const light = block(':host');
const dark = block(':host([dark])');

